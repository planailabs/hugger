@rt("/api/archive", methods=["POST"])
async def api_archive(req):
    body = {}
    try:
        body = await req.json()
    except Exception:
        form = await req.form()
        body = dict(form)
    repo_id = (body.get("repo_id") or "").strip()
    if not repo_id:
        return JSONResponse({"error": "repo_id required"}, status_code=400)
    revision = (body.get("revision") or "main").strip()
    job = jobs.manager.start(repo_id, revision)
    return JSONResponse({"job_id": job.id, "repo_id": repo_id})


@rt("/api/status/{job_id}", methods=["GET"])
def api_status(job_id: str):
    job = jobs.manager.get(job_id)
    if not job:
        return JSONResponse({"error": "not found"}, status_code=404)
    return JSONResponse(job.as_dict())


@rt("/api/archives", methods=["GET"])
def api_archives():
    return JSONResponse({"archives": store.list_archives()})


@rt("/api/archive/{repo_id:path}", methods=["GET"])
def api_archive_status(req):
    """Whether a specific repo is archived — used by the extension to decide
    between offering Archive vs Remove/Update. Takes `req` (not a body-sourced
    param) so a stray Content-Type header can't trigger body parsing."""
    repo_id = req.path_params["repo_id"]
    rec = store.get_archive(repo_id)
    if not rec:
        return JSONResponse({"repo_id": repo_id, "archived": False})
    return JSONResponse({
        "repo_id": repo_id,
        "archived": True,
        "sha": rec["sha"],
        "size_bytes": rec["size_bytes"],
        "update_available": bool(rec["update_available"]),
    })


@rt("/api/archive/{repo_id:path}", methods=["DELETE"])
def api_archive_delete(req):
    repo_id = req.path_params["repo_id"]
    jobs.delete_archive(repo_id)
    return JSONResponse({"ok": True, "repo_id": repo_id})


