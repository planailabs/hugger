def file_list(files: list[dict], *, submit_buttons: list, signals: dict | None = None,
              preselect=None, statuses: dict | None = None, removable_repo: str | None = None,
              disabled=None):
    """Reusable Datastar file picker. Checkboxes bind to a `files` array signal
    (its initial value = the preselected, non-disabled paths); `submit_buttons`
    are Datastar actions that read it. `signals` seeds extra picker signals (repo,
    store, mode…). `disabled` paths can't be selected; `removable_repo` adds a
    per-file Remove action."""
    preselect = preselect if preselect is not None else {f["path"] for f in files}
    disabled = disabled or set()
    selected = [f["path"] for f in files if f["path"] in preselect and f["path"] not in disabled]
    seed = {"files": selected, "mode": "all", **(signals or {})}
    head = [Th("File"), Th("Size", cls="r")]
    if statuses is not None:
        head.append(Th("Status"))
    if removable_repo:
        head.append(Th("", cls="r"))
    rows = []
    for f in files:
        is_disabled = f["path"] in disabled
        cells = [
            # checkbox + filename together in the File cell (label), per the design
            Td(Label(
                Input(type="checkbox", value=f["path"], disabled=is_disabled,
                      **{"data-bind": "files"}),
                Span(f["path"], cls="mono wrap"),
                cls="fcheck",
            )),
            Td(human_size(f["size"]), cls="muted r"),
        ]
        status = statuses.get(f["path"]) if statuses is not None else None
        if statuses is not None:
            cells.append(Td(status_pill(status)))
        if removable_repo:
            rm = (ds_button("Remove", f"@post('/ui/file-remove/{removable_repo}?path={quote(f['path'])}')",
                            indicator=_sig("rm", f["path"]), cls="danger")
                  if status in ("downloaded", "bad") else "")
            cells.append(Td(rm))
        rows.append(Tr(*cells))
    return Div(
        Div(Table(Thead(Tr(*head)), Tbody(*rows)), cls="filelist"),
        Div(*submit_buttons, cls="row"),
        **{"data-signals": json.dumps(seed)},
    )


def file_statuses(repo_id: str, files: list[dict]):
    """Per-file status (downloaded / downloading / missing) + the set of paths
    that are currently downloading (and so can't be selected)."""
    rec = store.get_archive(repo_id)
    downloading = jobs.manager.active_download_files(repo_id)
    bad = set(metadata.read_bad(rec["path"]).get("files", [])) if rec else set()
    statuses = {}
    for f in files:
        if f["path"] in downloading:
            statuses[f["path"]] = "downloading"
        elif f["path"] in bad:
            statuses[f["path"]] = "bad"  # failed verification
        elif rec and metadata.file_downloaded(rec["path"], f["path"], f["size"]):
            statuses[f["path"]] = "downloaded"
        else:
            statuses[f["path"]] = "missing"
    locked = {p for p, s in statuses.items() if s == "downloading"}
    return statuses, locked


# --- security middleware -------------------------------------------------

# All scripts are self-hosted from /static (no CDN, no inline script), so
# script-src is just 'self' plus 'unsafe-eval' — which Datastar needs to evaluate
# data-* expressions via the Function constructor. SSE actions use same-origin
# fetch (connect-src).
_CSP = (
    "default-src 'self'; "
    "script-src 'self' 'unsafe-eval'; "
    "style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self'"
)


class SecurityHeaders:
    """Pure-ASGI security-header middleware. Pure ASGI (not BaseHTTPMiddleware) so
    it doesn't wrap streaming responses in a memory stream — that buffering hurts
    SSE flushing and throws a CancelledError traceback when long-lived streams are
    cancelled on shutdown."""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            return await self.app(scope, receive, send)
        if scope["method"] in ("GET", "HEAD"):
            scope = dict(scope, headers=[h for h in scope["headers"] if h[0] != b"content-type"])

        async def send_with_headers(message):
            if message["type"] == "http.response.start":
                h = MutableHeaders(scope=message)
                h["X-Content-Type-Options"] = "nosniff"
                h["X-Frame-Options"] = "DENY"
                h["Referrer-Policy"] = "no-referrer"
                h["Content-Security-Policy"] = _CSP
                if cfg.https_only:
                    h["Strict-Transport-Security"] = "max-age=31536000; includeSubDomains"
            await send(message)

        await self.app(scope, receive, send_with_headers)


def _middleware() -> list:
    mw = [Middleware(TrustedHostMiddleware, allowed_hosts=cfg.allowed_hosts)]
    if cfg.allowed_origins:
        mw.append(
            Middleware(
                CORSMiddleware,
                allow_origins=cfg.allowed_origins,
                allow_methods=["GET", "POST", "DELETE"],
                allow_headers=["authorization", "x-hugger-token", "content-type"],
            )
        )
    mw.append(Middleware(SecurityHeaders))
    return mw


# --- auth gate -----------------------------------------------------------

def _before(req, sess):
    path = req.url.path
    if path.startswith("/api/"):
        if not auth.verify_token(auth.bearer_from_request(req)):
            return JSONResponse({"error": "unauthorized"}, status_code=401)
        return  # token ok -> allow
    if not sess.get("auth"):
        return RedirectResponse("/login", status_code=303)
    # Force an autogenerated password to be changed before anything else.
    if auth.must_change_password() and path not in ("/change-password", "/logout"):
        return RedirectResponse("/change-password", status_code=303)


beforeware = Beforeware(
    _before,
    skip=[r"/favicon\.ico", r"/static/.*", r".*\.css", r".*\.js", "/login"],
)


