@rt("/change-password", methods=["POST"])
def change_password(sess, new: str = "", confirm: str = ""):
    if len(new) < 6:
        return RedirectResponse("/change-password?error=Password+too+short+(min+6)", status_code=303)
    if new != confirm:
        return RedirectResponse("/change-password?error=Passwords+do+not+match", status_code=303)
    auth.set_password(new, autogenerated=False)  # clears the must-change flag
    return RedirectResponse("/", status_code=303)


