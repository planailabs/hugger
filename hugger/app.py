# --- bootstrap secrets / password ----------------------------------------

def _bootstrap_password() -> None:
    """Ensure a password exists. Env HUGGER_PASSWORD sets/updates it; otherwise a
    random one is generated, printed once, and flagged so the user is forced to
    change it on first login."""
    env_pw = os.environ.get("HUGGER_PASSWORD")
    if env_pw:
        auth.set_password(env_pw, autogenerated=False)
        return
    if not auth.has_password():
        generated = secrets.token_urlsafe(12)
        auth.set_password(generated, autogenerated=True)
        banner = (
            "=" * 60
            + "\n hugger: no password set — generated an initial one:"
            + f"\n   PASSWORD: {generated}"
            + "\n   You'll be required to change it on first login.\n"
            + "=" * 60
        )
        print(banner, flush=True)


# --- helpers -------------------------------------------------------------

def human_size(n: int) -> str:
    f = float(n)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if f < 1024 or unit == "TB":
            return f"{f:.0f} {unit}" if unit == "B" else f"{f:.1f} {unit}"
        f /= 1024
    return f"{f:.1f} TB"


def human_rate(bytes_per_sec: float) -> str:
    return f"{human_size(bytes_per_sec)}/s" if bytes_per_sec > 0 else ""


def human_eta(seconds: int | None) -> str:
    """Compact remaining-time, e.g. '45s', '3m 20s', '1h 4m'."""
    if seconds is None or seconds < 0:
        return ""
    if seconds < 60:
        return f"{seconds}s"
    m, s = divmod(seconds, 60)
    if m < 60:
        return f"{m}m {s}s"
    h, m = divmod(m, 60)
    return f"{h}h {m}m"


async def _ds_csrf_ok(req, sess) -> bool:
    """CSRF check for Datastar actions: the token rides as the `csrf` signal
    (sent in the JSON body for POST, the `datastar` query for GET)."""
    signals = await read_signals(req) or {}
    return auth.csrf_ok(sess, signals.get("csrf"))


